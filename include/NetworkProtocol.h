#pragma once
#include "raylib.h"

// NetworkProtocol.h
// 网络通信协议定义
//
// 本文件定义了双人联机模式下网络传输的数据结构
// 使用ENet库进行UDP通信，采用客户端-服务器架构
//
// 通信流程：
//   1. 主机创建房间，等待客户端连接
//   2. 客户端连接主机，建立连接
//   3. 主机：每帧发送GameState给客户端（约30fps）
//   4. 客户端：每帧发送本地挡板X坐标给主机
//   5. 主机：接收客户端挡板位置用于碰撞检测
//   6. 客户端：接收主机游戏状态用于插值渲染
//
// 注意事项：
//   - 网络包使用UDP协议，可能丢包，因此客户端需要插值平滑显示
//   - 使用ENET_PACKET_FLAG_UNSEQUENCED标志，不保证顺序但降低延迟
//   - 当前版本不支持断线重连

// struct GameState
// 游戏状态结构体（旧版，保留用于兼容）
// 定义了需要在网络上同步的游戏状态数据
// 通过网络包在主机和客户端之间传输
//
// 同步的数据包括：
//   - 小球位置和速度（客户端需要这些来渲染对手的半场）
//   - 双方挡板位置（用于显示对手挡板）
//   - 双方分数（用于UI显示）
//
// 注意：当前实际使用的是下面NetworkGameState结构体
//       本结构体已废弃，保留仅为兼容旧代码
struct GameState {
    float ballX, ballY;         // 小球中心位置坐标
    float ballSpeedX, ballSpeedY; // 小球速度向量（像素/秒）
    float paddle1X;             // 玩家1（主机）的挡板X坐标
    float paddle2X;             // 玩家2（客户端）的挡板X坐标
    int score1, score2;         // 双方当前分数
};

// struct NetworkGameState
// 网络游戏状态结构体（正式版本）
// 定义了在主机和客户端之间同步的完整游戏状态
//
// 为什么需要这个结构体：
//   - 双人模式下，客户端需要知道小球的完整状态才能正确渲染
//   - 主机负责所有碰撞检测和游戏逻辑，客户端只负责显示和发送输入
//   - 避免双方逻辑不一致导致的不同步问题
//
// 数据流向：
//   - 主机 -> 客户端：完整的GameState（小球位置、速度、双方分数）
//   - 客户端 -> 主机：仅挡板X坐标（因为主机不需要客户端的其他状态）
//
// 包大小：
//   - 本结构体包含5个float + 2个int = 28字节（在64位系统上）
//   - 适合高频发送（30fps），不会造成网络负担
struct NetworkGameState {
    float ballX, ballY;         // 小球中心位置坐标（主机计算的权威值）
    float ballSpeedX, ballSpeedY; // 小球速度向量（主机计算的权威值）
    float paddle1X;             // 主机挡板的X坐标
    float paddle2X;             // 客户端挡板的X坐标（主机收到后存储并转发）
    int score1, score2;         // 双方当前分数（主机计算的权威值）
};

// 网络通信说明：
//
// 1. 主机端发送包格式：
//    - 数据：NetworkGameState结构体（28字节）
//    - 频率：约30fps（由networkSendTimer控制）
//    - 标志：ENET_PACKET_FLAG_UNSEQUENCED（不保证顺序，但降低延迟）
//
// 2. 客户端发送包格式：
//    - 数据：float（挡板X坐标，4字节）
//    - 频率：约30fps
//    - 标志：ENET_PACKET_FLAG_UNSEQUENCED
//
// 3. 客户端插值算法：
//    - 客户端收到主机状态时记录时间戳
//    - 在两个状态之间进行线性插值：P = P0 * (1-alpha) + P1 * alpha
//    - 插值因子alpha = (当前时间 - 上一状态时间) / (两状态间隔)
//    - 插值后可平滑显示对手动作，即使网络有抖动
//
// 4. 超时处理：
//    - 5秒内未收到对方数据包，判定连接断开
//    - 自动降级为单人模式继续游戏
//
// 端口信息：
//   - 默认端口：12345
//   - 主机监听0.0.0.0:12345
//   - 客户端连接到<服务器IP>:12345